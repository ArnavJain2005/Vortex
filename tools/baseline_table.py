"""Per-sequence baseline table: an estimator tag against the never-moving floor tag, clean and on the
official-script copies (both column readings; seeds 1..3 as a mean, seed 42 apart). Reads
Docs/results/<tag>.json written by tools/eval_euroc.py; writes Docs/<out>.md. Never edit that file by hand.

    python tools/baseline_table.py --est step2-off --floor step2-floor-off --clean step2-clean
                                   --floor-clean step2-floor-clean --out STEP2_BASELINE
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "Docs", "results")
HELD_OUT = ("MH_03", "MH_04", "MH_05", "V1_01", "V1_02", "V1_03")


def load(tag):
    with open(os.path.join(RES, tag + ".json"), encoding="utf-8") as f:
        return json.load(f)


def mean(xs):
    xs = [x for x in xs if x is not None]
    return sum(xs) / len(xs) if xs else None


def f(x, d=2):
    return "-" if x is None else "%.*f" % (d, x)


def group(results, base, reading, seeds):
    return [r for r in results if "error" not in r and r["base"] == base and r["reading"] == reading
            and r["seed"] in seeds]


def build(a):
    est, flo = load(a["est"]), load(a["floor"])
    ce, cf = load(a["clean"]), load(a["floor_clean"])
    bases = sorted({r["base"] for r in est["results"] if "base" in r})
    L = ["# Step 2 baseline: shipped estimator against the never-moving floor (generated by "
         "`python tools/baseline_table.py`; do not edit by hand)", "",
         "Estimator: `main.py` at %s (shipped settings + the Step 2 input front end). Floor: "
         "`tools/baseline_still.py` (one identity pose per row at the origin), scored the same way. APE = "
         "RMSE after SE3 Umeyama fitted on the run being scored. Gap = mean RMSE inside missing-row bursts "
         "(>= 5 rows). Blind = RMSE over the last 5 s (exact zeros). Copies: the organisers' "
         "`degrade_imu.py` via `tools/official_degrade.py`; reading a = raw EuRoC (gyro first) fed in, "
         "reading b = reordered accel first. Tuning sequences: MH_01, MH_02; the rest are held out. "
         "Seed 42 (the script's own) is for reporting only." % est["commit"], "",
         "## Per sequence: estimator / floor, APE SE3 m", "",
         "| Sequence | Set | Clean | a, seeds 1..3 | a, seed 42 | b, seeds 1..3 | b, seed 42 |",
         "|---|---|---|---|---|---|---|"]
    cleanE = {r["sequence"]: r for r in ce["results"] if "error" not in r}
    cleanF = {r["sequence"]: r for r in cf["results"] if "error" not in r}
    for b in bases:
        cells = ["%s / %s" % (f(cleanE.get(b, {}).get("ate_se3_rmse")), f(cleanF.get(b, {}).get("ate_se3_rmse")))]
        for reading in ("a", "b"):
            for seeds in ((1, 2, 3), (42,)):
                e = mean([r["ape_se3_rmse"] for r in group(est["results"], b, reading, seeds)])
                fl = mean([r["ape_se3_rmse"] for r in group(flo["results"], b, reading, seeds)])
                cells.append("%s / %s" % (f(e), f(fl)))
        L.append("| %s | %s | %s |" % (b, "held out" if b.startswith(HELD_OUT) else "tuning", " | ".join(cells)))

    L += ["", "## Means: estimator / floor", "",
          "| Set | Reading | Seeds | Copies | APE SE3 m | RPE 1 s m | Gap RMSE m | Blind RMSE m | Blind growth m "
          "| Contract |", "|---|---|---|---|---|---|---|---|---|---|"]
    for setname, sel in (("held out", lambda b: b.startswith(HELD_OUT)), ("tuning", lambda b: not b.startswith(HELD_OUT)),
                         ("all", lambda b: True)):
        for reading in ("a", "b"):
            for lab, seeds in (("1..3", (1, 2, 3)), ("42", (42,))):
                rs = [r for b in bases if sel(b) for r in group(est["results"], b, reading, seeds)]
                fs = [r for b in bases if sel(b) for r in group(flo["results"], b, reading, seeds)]
                if not rs:
                    continue
                cells = []
                for k, d in (("ape_se3_rmse", 2), ("rpe200_rmse", 3), ("gap_rmse_mean", 2), ("blind_rmse", 2),
                             ("blind_growth", 2)):
                    cells.append("%s / %s" % (f(mean([r[k] for r in rs]), d), f(mean([r[k] for r in fs]), d)))
                ok = sum(r["contract"] == "PASS" for r in rs)
                L.append("| %s | %s | %s | %d | %s | %d/%d PASS |" % (setname, reading, lab, len(rs), " | ".join(cells),
                                                                     ok, len(rs)))
    ce_ok = [r for r in ce["results"] if "error" not in r]
    L += ["", "## Clean (undegraded) means: estimator / floor", "",
          "| Set | Sequences | APE SE3 m | RPE 1 s m |", "|---|---|---|---|"]
    for setname, sel in (("held out", lambda b: b.startswith(HELD_OUT)), ("tuning", lambda b: not b.startswith(HELD_OUT)),
                         ("all", lambda b: True)):
        names = [r["sequence"] for r in ce_ok if sel(r["sequence"])]
        L.append("| %s | %d | %s / %s | %s / %s |" % (
            setname, len(names), f(mean([cleanE[n]["ate_se3_rmse"] for n in names])),
            f(mean([cleanF[n]["ate_se3_rmse"] for n in names if n in cleanF])),
            f(mean([cleanE[n]["rpe200_rmse"] for n in names]), 3),
            f(mean([cleanF[n]["rpe200_rmse"] for n in names if n in cleanF]), 3)))
    errs = [r["sequence"] for t in (est, flo, ce, cf) for r in t["results"] if "error" in r]
    L += ["", "Runs with errors: %s" % (", ".join(errs) if errs else "none"), ""]
    return "\n".join(L)


def main(argv):
    get = lambda k, d=None: argv[argv.index(k) + 1] if k in argv else d  # noqa: E731
    a = {"est": get("--est"), "floor": get("--floor"), "clean": get("--clean"), "floor_clean": get("--floor-clean"),
         "out": get("--out", "STEP2_BASELINE")}
    if not all(a.values()):
        print(__doc__)
        return 2
    text = build(a)
    path = os.path.join(ROOT, "Docs", a["out"] + ".md")
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
