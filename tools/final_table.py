"""The final table (Docs/TRACK3_PLAN.md, "Final table"): an estimate tag against the never-moving floor tag, on
official copies scored by tools/eval_euroc.py --official. Committed with the plan, BEFORE the V2 copies exist.
Stdlib only; never edit its output by hand.

    python tools/final_table.py --est final-v10-V2 --floor final-floor-V2 [--out Docs/FINAL_TABLE.md]

Per sequence and reading, per sequence (both readings), per reading and pooled over every copy: mean APE (SE(3)
fitted on the run being scored), mean gap RMSE, mean blind RMSE, for the estimate and the floor, and
100 (est / floor - 1) (negative = better than standing still). Also the output-contract PASS count and how many
sequences beat the floor on pooled APE. A copy with an error is listed, never dropped silently.
"""
import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RESULTS = os.path.join(ROOT, "Docs", "results")
METRICS = (("ape_se3_rmse", "APE"), ("gap_rmse_mean", "gap RMSE"), ("blind_rmse", "blind RMSE"))


def load(tag, results=RESULTS):
    with open(os.path.join(results, tag + ".json"), encoding="utf-8") as f:
        return json.load(f)


def mean(xs):
    xs = [x for x in xs if x is not None]
    return sum(xs) / len(xs) if xs else None


def pct(a, b):
    return None if a is None or not b else 100.0 * (a / b - 1.0)


def f3(x):
    return "-" if x is None else "%.3f" % x


def fp(x):
    return "-" if x is None else "%+.1f %%" % x


def rows(est, floor):
    """[(estimate result, floor result)] for every copy scored in both; plus the copies with an error."""
    fl = {r["sequence"]: r for r in floor["results"]}
    pairs, bad = [], []
    for r in est["results"]:
        f = fl.get(r["sequence"])
        if "error" in r or f is None or "error" in f:
            bad.append(r["sequence"])
        else:
            pairs.append((r, f))
    return pairs, bad


def group_line(label, ps):
    cells = [label, "%d" % len(ps)]
    for key, _ in METRICS:
        a, b = mean([e.get(key) for e, _ in ps]), mean([f.get(key) for _, f in ps])
        cells += ["%s / %s" % (f3(a), f3(b)), fp(pct(a, b))]
    return "| " + " | ".join(cells) + " |"


def build(est, floor):
    pairs, bad = rows(est, floor)
    seqs = sorted({e["base"] for e, _ in pairs})
    head = "| Group | Copies | " + " | ".join("%s: Vortex / floor (m) | %s vs floor" % (n, n) for _, n in METRICS) + " |"
    sep = "|---|---:" + "|---:|---:" * len(METRICS) + "|"
    out = ["# Final table", "",
           "Generated by `python tools/final_table.py --est %s --floor %s`; never edit by hand." % (est["tag"], floor["tag"]),
           "", "- Estimate: `%s` (commit %s, main `%s`, Python %s, %s)." % (
               est["tag"], est.get("commit"), est.get("main"), est.get("python"), est.get("date")),
           "- Floor: `%s` (never moving, scored the same way; commit %s, %s)." % (
               floor["tag"], floor.get("commit"), floor.get("date")),
           "- APE: SE(3) Umeyama fitted on the run being scored. Gap RMSE: inside missing-row bursts. Blind RMSE: the",
           "  final dead-sensor window. Both windows from each copy's `degrade.json`. Means are over copies.",
           "- Output contract: %d/%d PASS." % (sum(1 for e, _ in pairs if e.get("contract") == "PASS"),
                                               len(est["results"]))]
    beat = sum(1 for s in seqs if mean([e["ape_se3_rmse"] for e, _ in pairs if e["base"] == s])
               < mean([f["ape_se3_rmse"] for e, f in pairs if e["base"] == s]))
    out.append("- Sequences better than the floor on pooled APE: %d/%d." % (beat, len(seqs)))
    if bad:
        out.append("- Copies with an error or no floor (NOT in the means): %s." % ", ".join(bad))
    out += ["", "## Pooled", "", head, sep, group_line("All copies", pairs)]
    for rd in "ab":
        ps = [p for p in pairs if p[0]["reading"] == rd]
        if ps:
            out.append(group_line("Reading %s" % rd, ps))
    out += ["", "## Per sequence (both readings)", "", head, sep]
    out += [group_line(s, [p for p in pairs if p[0]["base"] == s]) for s in seqs]
    out += ["", "## Per sequence and reading", "", head, sep]
    for s in seqs:
        for rd in "ab":
            ps = [p for p in pairs if p[0]["base"] == s and p[0]["reading"] == rd]
            if ps:
                out.append(group_line("%s, reading %s" % (s, rd), ps))
    out += ["", "## Per copy", "", "| Copy | Contract | APE Vortex / floor (m) | gap RMSE (m) | blind RMSE (m) |",
            "|---|---|---:|---:|---:|"]
    for e, f in sorted(pairs, key=lambda p: p[0]["sequence"]):
        out.append("| %s | %s | %s / %s | %s / %s | %s / %s |" % (
            e["sequence"], e.get("contract"), f3(e.get("ape_se3_rmse")), f3(f.get("ape_se3_rmse")),
            f3(e.get("gap_rmse_mean")), f3(f.get("gap_rmse_mean")), f3(e.get("blind_rmse")), f3(f.get("blind_rmse"))))
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--est", required=True)
    ap.add_argument("--floor", required=True)
    ap.add_argument("--out", default=os.path.join(ROOT, "Docs", "FINAL_TABLE.md"))
    a = ap.parse_args(argv)
    text = build(load(a.est), load(a.floor))
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
