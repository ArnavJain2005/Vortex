"""Summarize paired official-script runs without touching the final V2 test set.

Usage: python tools/diagnose_official.py > Docs/DIAGNOSIS.md
The input JSON files are generated by tools/eval_euroc.py. This script reads
recorded metrics only; it does not run an estimator or access ground truth.
"""

import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SETS = (
    ("Step F, seeds 4–6", "stepF-H-p0v-refresh", "stepF-H-floor"),
    ("Step L1 repeat, seeds 7–9", "stepL1-H-off", "stepL1-H-floor"),
)
FIELDS = ("ape_se3_rmse", "rpe200_rmse", "gap_rmse_mean", "blind_rmse", "blind_growth")


def paired(est_tag, floor_tag):
    def load(tag):
        path = ROOT / "Docs" / "results" / (tag + ".json")
        data = json.loads(path.read_text(encoding="utf-8"))
        if not data["official"]:
            raise ValueError(f"{tag}: expected official-script input")
        runs = data["results"]
        if any(r["base"].startswith("V2_") for r in runs):
            raise ValueError(f"{tag}: final V2 sequences must remain sealed")
        result = {r["sequence"]: r for r in runs}
        if len(result) != len(runs):
            raise ValueError(f"{tag}: duplicate sequence")
        return result

    est, floor = load(est_tag), load(floor_tag)
    if est.keys() != floor.keys():
        raise ValueError(f"unpaired copies: {est.keys() ^ floor.keys()}")
    pairs = []
    for name in sorted(est):
        a, b = est[name], floor[name]
        if (a["base"], a["reading"], a["seed"], a["rows"]) != (
            b["base"], b["reading"], b["seed"], b["rows"]
        ) or a["contract"] != "PASS" or b["contract"] != "PASS":
            raise ValueError(f"mismatched or invalid copy: {name}")
        pairs.append((a, b))
    return pairs


def mean(pairs, index, field):
    return sum(p[index][field] for p in pairs) / len(pairs)


def fmt(pairs, field):
    return f"{mean(pairs, 0, field):.3f} / {mean(pairs, 1, field):.3f}"


def section(title, est_tag, floor_tag):
    pairs = paired(est_tag, floor_tag)
    if len(pairs) != 36:
        raise ValueError(f"{est_tag}: expected 36 paired copies, got {len(pairs)}")
    groups = sorted({(a["base"], a["reading"]) for a, _ in pairs})
    out = [f"## {title}", "", f"Source: `{est_tag}.json` paired with `{floor_tag}.json` by copy name; "
           "three seeds per sequence and reading. Entries are arithmetic means of per-copy metrics, "
           "**estimator / stationary floor**, in metres. RPE is the one-second translational metric.", "",
           "| Sequence | Reading | APE SE(3) | RPE 1 s | Gap RMSE | Blind RMSE | Blind growth |",
           "|---|:---:|---:|---:|---:|---:|---:|"]
    for base, reading in groups:
        subset = [(a, b) for a, b in pairs if (a["base"], a["reading"]) == (base, reading)]
        values = " | ".join(fmt(subset, field) for field in FIELDS)
        out.append(f"| {base} | {reading} | {values} |")
    out.extend(["", "| Reading | Copies | APE SE(3) | RPE 1 s | Gap RMSE | Blind RMSE | Blind growth |",
                "|:---:|---:|---:|---:|---:|---:|---:|"])
    for reading in "ab":
        subset = [(a, b) for a, b in pairs if a["reading"] == reading]
        values = " | ".join(fmt(subset, field) for field in FIELDS)
        out.append(f"| {reading} | {len(subset)} | {values} |")
    return "\n".join(out)


def main():
    print("# Official degradation: paired failure map\n")
    print("Generated by `python tools/diagnose_official.py > Docs/DIAGNOSIS.md` from committed "
          "`Docs/results/*.json`. The script reads recorded aggregate metrics only. It does not "
          "measure per-row attitude, error onset or error at the blind-window boundary. "
          "Vicon Room 2 is not read.\n")
    for title, est_tag, floor_tag in SETS:
        print(section(title, est_tag, floor_tag), "\n")
    print("## What these results support\n")
    print("- Reading a has large, repeatable APE and blind-window deficits on MH_03–05 and V1_01. "
          "Reading b is better on most Machine Hall copies, but does not reliably beat the floor "
          "on V1_02/03. A single pooled mean conceals both behaviors.\n"
          "- Blind RMSE is much larger than the measured blind growth on the worst reading-a cases. "
          "This is consistent with error already present at sensor failure, but the aggregate "
          "metrics cannot isolate the starting pose error.\n"
          "- Step L1's seeds 7–9 repeat patterns on the same six sequences. They are a robustness "
          "check, not an independent validation set.\n")
    print("## Next diagnostic (requires local IMU, estimates and scoring ground truth)\n")
    print("1. For each copy, score fixed-duration windows from the protected 2 s through the blind "
          "boundary, fitting SE(3) **once per whole copy** and reusing that transform for each "
          "window. Keep the stationary floor paired to the same timestamps.\n"
          "2. Log input-only gyro/acceleration norms, robust short-window variation, stillness "
          "decisions, bias estimates and attitude change; compare with clean-input and "
          "ground-truth orientation only in offline analysis.\n"
          "3. Report the pose error at the last valid sample and the change of the error vector "
          "through the blind phase. Then choose one causal intervention and register its rule "
          "before any new held-out run.\n")
    print("**Decision boundary:** no estimator change follows from these aggregates alone. "
          "The recorded Step 3 fault switches and Step L1 shrink switch remain off. "
          "Reserve V2_01–03 for the final table.\n")


if __name__ == "__main__":
    main()
